def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default="out", help="root holding online_sim / online_real")
    ap.add_argument("--out", required=True, help="where to write the package")
    ap.add_argument("--team", default="大师赛第一期赛题2—【固态蜗牛队】—【张煜晨】—【156****6887】")
    ap.add_argument("--no-zip", action="store_true")
    a = ap.parse_args()

    checks = []
    have = {}
    for key, _label, sub in SOURCES:
        h = audit_source(key, sub, a.root, checks)
        if h:
            have[key] = h

    os.makedirs(a.out, exist_ok=True)
    pkg = os.path.join(a.out, a.team)
    os.makedirs(pkg, exist_ok=True)
    for key, _label, sub in SOURCES:
        if key not in have:
            continue
        dst = os.path.join(pkg, sub)
        os.makedirs(dst, exist_ok=True)
        h = have[key]
        for src, nm in ((h["pcd"], "map.pcd"), (h["summary"], "summary.json"),
                        (h["table"], "label_table.yaml"),
                        (os.path.join(os.path.dirname(h["pcd"]), "frames.csv"),
                         "frames.csv")):
            if os.path.exists(src):
                shutil.copy2(src, os.path.join(dst, nm))
    write_readme(os.path.join(pkg, "README.md"), have, a.root)

    # videos are copied last: they are the large ones and the least likely to
    # have changed, so a failure earlier in the copy is noticed before the wait
    for key, _label, sub in SOURCES:
        if key in have and os.path.exists(have[key]["video"]):
            shutil.copy2(have[key]["video"],
                         os.path.join(pkg, sub, "run.mp4"))

    # ---- cross-source consistency ----
    if len(have) == 2 and all(os.path.exists(have[k]["table"]) for k in have):
        tabs = []
        for key in have:
            ids, names = read_label_table(have[key]["table"])
            tabs.append((key, ids, names))
        same = tabs[0][1] == tabs[1][1]
        checks.append(("PASS" if same else "FAIL",
                       "both sources use the same label table (%d ids)"
                       % len(tabs[0][1]), ""))
    elif len(have) == 2:
        checks.append(("FAIL", "cannot compare label tables between sources",
                       "one of the two is missing"))
    elif len(have) == 1:
        checks.append(("WARN", "only one source present in --root; the brief "
                       "asks for both", ",".join(have)))

    total_mb = 0.0
    for root, _dirs, files in os.walk(pkg):
        for f in files:
            total_mb += os.path.getsize(os.path.join(root, f)) / 1e6
    checks.append(("PASS" if total_mb <= MAX_ARCHIVE_MB else "FAIL",
                   "package contents %.1f MB (limit %.0f MB)"
                   % (total_mb, MAX_ARCHIVE_MB), ""))

    # ---- write the archive, but never over a good one --------------------
    # This guard exists because the tool shipped a broken package once.  The
    # real-side pcd had been truncated by a download that was interrupted
    # part-way; the audit caught it and printed FAIL -- and then zipped anyway,
    # overwriting the previous, correct archive with the broken one.  An audit
    # that reports a problem and then destroys the last good artifact is worse
    # than no audit at all.
    #
    # So: FAIL anywhere before this point means the archive is NOT written.
    # The staged directory (and its own files) still gets updated, because that
    # is what you want to inspect while fixing the problem.
    n_fail_so_far = sum(1 for k, _m, _e in checks if k == "FAIL")
    if not a.no_zip and n_fail_so_far:
        checks.append(("FAIL", "archive NOT written: %d check(s) failed above"
                       % n_fail_so_far,
                       "the previous archive is left untouched on purpose"))
        zpath = None
    elif not a.no_zip:
        zpath = os.path.join(a.out, a.team + ".zip")
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for root, _dirs, files in os.walk(pkg):
                for f in files:
                    full = os.path.join(root, f)
                    z.write(full, os.path.relpath(full, a.out))
        zmb = os.path.getsize(zpath) / 1e6
        checks.append(("PASS" if zmb <= MAX_ARCHIVE_MB else "FAIL",
                       "archive %.1f MB (limit %.0f MB)" % (zmb, MAX_ARCHIVE_MB),
                       zpath))
        checks.append(("info", "archive md5 below", ""))
        h = hashlib.md5()
        with open(zpath, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                h.update(chunk)
        checks.append(("info", "md5 %s  (%d B)" % (h.hexdigest(),
                                                   os.path.getsize(zpath)), zpath))

    print("\n=== 终审 / final audit ===")
    n_fail = 0
    n_warn = 0
    for kind, msg, extra in checks:
        if kind == "FAIL":
            n_fail += 1
        if kind == "WARN":
            n_warn += 1
        print("  [%-4s] %s" % (kind, msg))
        if extra and kind in ("FAIL", "WARN"):
            print("           %s" % extra)
    print("\n  %d FAIL, %d WARN" % (n_fail, n_warn))
    print("  verdict: %s" % ("PASS" if n_fail == 0 else "FAIL"))
    return 1 if n_fail else 0


if __name__ == "__main__":
    raise SystemExit(main())
