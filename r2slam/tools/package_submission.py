#!/usr/bin/env python3
"""Assemble and audit the round-2 submission package.

The organisers ask for three things -- a simulator video, a real-dataset video
and the built pcd -- plus a named archive.  Two of those are generated by
`online_pipeline.py`; this script is the **final review** step, and it exists
because round 1 was lost points to details that no one would notice by eye:

  * the recording limit appears in two organiser documents with *different*
    numbers (5 min on the contest page, 2 min in the shipped guide).  We build
    to the stricter one and the script checks it rather than trusting memory.
  * the FAQ does not publish a class table, so the package has to carry one.
    A pcd whose `label` column has no lookup is a pcd a judge cannot read.
  * `POINTS` in the pcd header, the byte count of the payload and the point
    count in `summary.json` are three independent statements of the same fact.
    They are checked against each other; a silent mismatch here means a
    truncated upload.

Every check prints PASS / FAIL / WARN and the script exits non-zero if anything
FAILs, so it can gate a release from a script instead of from a human's memory.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import zipfile

import numpy as np

# The stricter of the two organiser documents (see module docstring).
MAX_VIDEO_S = 120.0
MAX_ARCHIVE_MB = 500.0

# The two data sources.  Named once so the audit cannot silently cover only one.
SOURCES = (("sim", "仿真环境 / simulator", "online_sim"),
           ("real", "真实数据集 / real dataset", "online_real"))


def find_ffprobe():
    exe = shutil.which("ffprobe")
    if exe:
        return exe
    try:
        import imageio_ffmpeg
        cand = os.path.join(os.path.dirname(imageio_ffmpeg.get_ffmpeg_exe()),
                            "ffprobe")
        for c in (cand, cand + ".exe"):
            if os.path.exists(c):
                return c
    except Exception:
        pass
    return None


def probe_video(path):
    ff = find_ffprobe()
    if not ff:
        return None
    r = subprocess.run([ff, "-v", "error", "-show_entries",
                        "format=duration,size",
                        "-show_entries",
                        "stream=codec_name,width,height,nb_frames",
                        "-of", "json", path],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return None
    try:
        j = json.loads(r.stdout)
    except Exception:
        return None
    st = (j.get("streams") or [{}])[0]
    fmt = j.get("format") or {}
    return {"duration": float(fmt.get("duration", 0.0)),
            "size": int(fmt.get("size", 0)),
            "codec": st.get("codec_name"),
            "width": int(st.get("width", 0)),
            "height": int(st.get("height", 0)),
            "nb_frames": int(st.get("nb_frames", 0)) if st.get("nb_frames") else None}


# Must match `worldmap.write_pcd`: 4+4+4+1+4 = 17 bytes per point.
PCD_DTYPE = [("x", "<f4"), ("y", "<f4"), ("z", "<f4"),
             ("label", "u1"), ("rgb", "<f4")]
PCD_STRIDE = 17


def read_pcd_header(path):
    with open(path, "rb") as fh:
        blob = fh.read(4096)
    marker = b"DATA binary\n"
    if marker not in blob:
        return None, 0, blob
    head = blob.split(marker)[0] + marker
    txt = head.decode("ascii", "replace")
    out = {}
    for line in txt.splitlines():
        parts = line.split()
        if parts:
            out[parts[0]] = parts[1:]
    return out, len(head), blob


def read_label_table(path):
    """Tiny reader for our own label_table.yaml -- no yaml dependency needed."""
    ids, names = set(), {}
    cur = None
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r"\s*-\s*id:\s*(\d+)", line)
            if m:
                cur = int(m.group(1))
                ids.add(cur)
                continue
            m = re.match(r"\s*name:\s*(\S+)", line)
            if m and cur is not None:
                names[cur] = m.group(1)
    return ids, names


def audit_source(key, label, out_root, checks):
    d = os.path.join(out_root, label)
    tag = "%s" % key
    mp4 = os.path.join(d, "run.mp4")
    pcd = os.path.join(d, "map.pcd")
    smy = os.path.join(d, "summary.json")
    tab = os.path.join(d, "label_table.yaml")

    checks.append(("info", "%s: %s" % (tag, d), ""))

    # ---- video ----
    if not os.path.exists(mp4):
        checks.append(("FAIL", "%s video missing" % tag, mp4))
        return None
    info = probe_video(mp4)
    if info is None:
        checks.append(("WARN", "%s video duration NOT verified (no ffprobe)"
                       % tag, mp4))
    else:
        ok = info["duration"] <= MAX_VIDEO_S
        checks.append(("PASS" if ok else "FAIL",
                       "%s video %.2f s (limit %.0f)  %dx%d %s"
                       % (tag, info["duration"], MAX_VIDEO_S, info["width"],
                          info["height"], info["codec"]), mp4))
        if info["width"] % 2 or info["height"] % 2:
            checks.append(("FAIL", "%s video has an odd dimension" % tag, ""))

    # ---- pcd ----
    if not os.path.exists(pcd):
        checks.append(("FAIL", "%s pcd missing" % tag, pcd))
        return None
    head, hlen, _ = read_pcd_header(pcd)
    if head is None:
        checks.append(("FAIL", "%s pcd is not binary or has no DATA line" % tag, ""))
        return None
    fields = head.get("FIELDS")
    npts = int(head.get("POINTS", ["0"])[0])
    want = ["x", "y", "z", "label", "rgb"]
    checks.append(("PASS" if fields == want else "FAIL",
                   "%s pcd FIELDS=%s (want %s)" % (tag, fields, want), ""))
    expect_bytes = hlen + npts * PCD_STRIDE
    actual = os.path.getsize(pcd)
    checks.append(("PASS" if actual == expect_bytes else "FAIL",
                   "%s pcd size %d B (header %d + %d pts x %d = %d)"
                   % (tag, actual, hlen, npts, PCD_STRIDE, expect_bytes), ""))

    # every label present in the file must be in the table
    if os.path.exists(tab):
        ids, names = read_label_table(tab)
        rec = np.fromfile(pcd, dtype=np.dtype(PCD_DTYPE), offset=hlen)
        present = sorted(int(v) for v in np.unique(rec["label"]))
        missing = [v for v in present if v not in ids]
        checks.append(("PASS" if not missing else "FAIL",
                       "%s pcd labels present %s; %s"
                       % (tag, present,
                          "all in the table" if not missing
                          else "MISSING FROM TABLE: %s" % missing), ""))
        checks.append(("PASS" if rec["label"].size == npts else "FAIL",
                       "%s pcd records read %d vs POINTS %d"
                       % (tag, rec["label"].size, npts), ""))
    else:
        checks.append(("FAIL", "%s label_table.yaml missing" % tag,
                       "the FAQ publishes no class table; the package must"))

    # ---- summary agreement ----
    if os.path.exists(smy):
        s = json.load(open(smy, encoding="utf-8"))
        m = s.get("map", {})
        same = int(m.get("points", -1)) == npts
        checks.append(("PASS" if same else "FAIL",
                       "%s summary points %s vs pcd POINTS %d"
                       % (tag, m.get("points"), npts), ""))
        checks.append(("info", "%s: %d frames, trajectory %.2f m, "
                       "traversable %.1f m2" % (tag, s.get("frames", -1),
                                                m.get("trajectory_len_m", -1),
                                                m.get("traversable_area_m2", -1)),
                       ""))
        nav = s.get("navigation")
        if nav and nav.get("enabled"):
            checks.append(("info", "%s navigation: '%s' -> %s, state %s"
                           % (tag, nav.get("query"), nav.get("resolved_to"),
                              nav.get("state")), ""))
        ins = s.get("instances")
        if ins and ins.get("n"):
            checks.append(("info", "%s instances: %s"
                           % (tag, ins.get("by_class")), ""))
    else:
        checks.append(("FAIL", "%s summary.json missing" % tag, ""))
    return {"video": mp4, "pcd": pcd, "summary": smy, "table": tab}


def unpaired_note(have) -> str:
    """The image-pairing shortfall, read from the run's own summary.

    Hard-coding a number here, or leaving a `%d` unformatted, is how a shipped
    README ends up telling a judge something that is not true about the run.
    The first version of this file did exactly that.
    """
    for key in ("real", "sim"):
        h = have.get(key)
        if not h:
            continue
        try:
            s = json.load(open(h["summary"], encoding="utf-8"))
        except Exception:
            continue
        ss = s.get("source_stamps") or {}
        if "unpaired" in ss:
            return ("%d / %d" % (ss["unpaired"], ss.get("paired_with_image", 0)
                                 + ss["unpaired"]))
    return "少量（本次运行的 summary.json 里未记录）"


